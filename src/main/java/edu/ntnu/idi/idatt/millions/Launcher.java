package edu.ntnu.idi.idatt.millions;

/**
 * Entry point used to launch the JavaFX application.
 *
 * <p>Delegates to {@link Main#main(String[])} so the app can be started from environments that
 * require a plain {@code public static void main} method.
 */
public class Launcher {

  /**
   * Launches the application.
   *
   * @param args command-line arguments
   */
  static void main(String[] args) {
    Main.main(args);
  }
}
